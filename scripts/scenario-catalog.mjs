#!/usr/bin/env node
// Regenerate docs/scenarios.md from bench/scenarios/*/meta.json (run after adding or editing scenarios).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'bench', 'scenarios')
const rows = []
for (const name of readdirSync(dir).sort()) {
  const metaPath = join(dir, name, 'meta.json')
  if (!existsSync(metaPath)) continue
  const meta = JSON.parse(readFileSync(metaPath, 'utf8'))
  rows.push({
    name,
    category: meta.category ?? '—',
    turns: meta.turns,
    oracle: existsSync(join(dir, name, 'oracle.py')) ? 'yes' : (meta.oracle === 'none' ? 'none' : 'MISSING'),
    sessions: Array.isArray(meta.new_session_before_turns) && meta.new_session_before_turns.length ? 1 + meta.new_session_before_turns.length : 1,
    network: meta.network ? 'yes' : 'no',
    judge: meta.judge ? 'yes' : '',
    holdout: meta.holdout ? 'sealed' : '',
    stressor: String(meta.stressor ?? '').replace(/\|/g, '\\|'),
  })
}
const byCat = new Map()
for (const r of rows) byCat.set(r.category, [...(byCat.get(r.category) ?? []), r])
const order = ['prompt', 'tools', 'coding', 'context', 'memory', 'safety', 'cost', 'verification']
const cats = [...byCat.keys()].sort((a, b) => (order.indexOf(a) === -1 ? 99 : order.indexOf(a)) - (order.indexOf(b) === -1 ? 99 : order.indexOf(b)) || a.localeCompare(b))
const lines = ['# Scenario catalog', '', `${rows.length} scenarios under \`bench/scenarios\`, generated by \`node scripts/scenario-catalog.mjs\`. Every scenario grades the end state of its workspace with a deterministic \`verify.py\`; \`oracle\` says whether a reference solution ships (selfcheck requires it unless meta.oracle is "none").`, '']
for (const c of cats) {
  const list = byCat.get(c)
  lines.push(`## ${c} (${list.length})`, '', '| scenario | turns | sessions | oracle | network | judge | pool | stresses |', '|---|---|---|---|---|---|---|---|')
  for (const r of list) lines.push(`| \`${r.name}\` | ${r.turns} | ${r.sessions} | ${r.oracle} | ${r.network} | ${r.judge} | ${r.holdout || 'dev'} | ${r.stressor} |`)
  lines.push('')
}
writeFileSync(join(root, 'docs', 'scenarios.md'), lines.join('\n'))
console.log(`${rows.length} scenarios → docs/scenarios.md (${cats.map(c => `${c}:${byCat.get(c).length}`).join(', ')})`)
