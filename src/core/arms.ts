/**
 * Arms: one complete configuration of the agent under test, expressed as
 * dsh patch overlays over a shared eval profile plus the SDK route (model,
 * effort). The runner passes each arm's overlay as `--patch`, so the tested
 * composition is exactly what dsh mounts — nothing is hand-wired.
 */
import { execFile } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { promisify } from 'node:util'
import yaml from 'js-yaml'
import type { ArmSpec, PatchRow, ResolvedArm } from './types.js'

const execFileAsync = promisify(execFile)

export class ArmError extends Error {}

export const DEFAULT_PROFILE = 'eval'
export const DEFAULT_PROVIDER = 'deepseek-official'
export const DEFAULT_MODEL = 'deepseek-v4-flash'

/** Parse an arm definition (YAML or JSON text). */
export function parseArm(text: string, sourcePath?: string): ArmSpec {
  const raw = yaml.load(text) as unknown
  if (raw === null || typeof raw !== 'object' || Array.isArray(raw)) throw new ArmError(`${sourcePath ?? 'arm'}: must be a mapping`)
  const r = raw as Record<string, unknown>
  if (typeof r['name'] !== 'string' || !/^[a-z0-9][a-z0-9._-]*$/i.test(r['name'])) {
    throw new ArmError(`${sourcePath ?? 'arm'}: name must be a short identifier (letters, digits, . _ -)`)
  }
  const patches = r['patches']
  if (patches !== undefined && !Array.isArray(patches)) throw new ArmError(`${r['name']}: patches must be a list of patch rows`)
  const spec: ArmSpec = { name: r['name'] }
  if (typeof r['description'] === 'string') spec.description = r['description']
  if (typeof r['profile'] === 'string') spec.profile = r['profile']
  if (typeof r['provider'] === 'string') spec.provider = r['provider']
  if (typeof r['model'] === 'string') spec.model = r['model']
  if (typeof r['effort'] === 'string') spec.effort = r['effort']
  if (typeof r['maxTokens'] === 'number') spec.maxTokens = r['maxTokens']
  if (Array.isArray(patches)) spec.patches = patches as PatchRow[]
  if (Array.isArray(r['patchFiles'])) spec.patchFiles = (r['patchFiles'] as unknown[]).map(String)
  if (r['env'] !== null && typeof r['env'] === 'object') spec.env = Object.fromEntries(Object.entries(r['env'] as Record<string, unknown>).map(([k, v]) => [k, String(v)]))
  return spec
}

export function loadArmFile(path: string): ArmSpec {
  const abs = resolve(path)
  if (!existsSync(abs)) throw new ArmError(`arm file not found: ${abs}`)
  const spec = parseArm(readFileSync(abs, 'utf8'), abs)
  return spec
}

/** Materialize an arm's overlay file under `outDir` and fill defaults. */
export function resolveArm(spec: ArmSpec, outDir: string, sourcePath?: string): ResolvedArm {
  mkdirSync(outDir, { recursive: true })
  const base = sourcePath !== undefined ? dirname(sourcePath) : process.cwd()
  const patchFilePaths = (spec.patchFiles ?? []).map(p => resolve(base, p))
  for (const p of patchFilePaths) if (!existsSync(p)) throw new ArmError(`${spec.name}: patch file not found: ${p}`)
  const overlayPath = join(outDir, `${spec.name}.patch.yml`)
  const rows = spec.patches ?? []
  writeFileSync(overlayPath, `# arm ${spec.name} — generated by dsh-eval; edit the arm file, not this overlay\n` + yaml.dump(rows, { lineWidth: 120, noRefs: true }))
  const resolved: ResolvedArm = {
    ...spec,
    profile: spec.profile ?? DEFAULT_PROFILE,
    provider: spec.provider ?? DEFAULT_PROVIDER,
    model: spec.model ?? DEFAULT_MODEL,
    overlayPath,
    patchFilePaths,
  }
  if (sourcePath !== undefined) resolved.sourcePath = sourcePath
  return resolved
}

/** All overlays the runner passes for an arm, in order: patch files, then the inline overlay. */
export function armOverlays(arm: ResolvedArm): string[] {
  return [...arm.patchFilePaths, arm.overlayPath]
}

export interface DshInvoker {
  /** Run the dsh CLI with args and env, resolving stdout. */
  (args: string[], env: Record<string, string>): Promise<string>
}

/** Default invoker: the `dsh` executable on PATH (or $DSH_BIN), with DSH_HOME pointed at the eval home. */
export const dshCli: DshInvoker = async (args, env) => {
  const bin = process.env['DSH_BIN'] ?? 'dsh'
  const { stdout } = await execFileAsync(bin, args, { env: { ...process.env, ...env }, maxBuffer: 32 * 1024 * 1024, timeout: 120_000 })
  return stdout
}

/** The composed profile tree as dsh would mount it: `dsh --profile P --dump-config --patch …`. */
export async function dumpComposedTree(evalHome: string, profile: string, overlays: string[], invoke: DshInvoker = dshCli): Promise<string> {
  const args = ['--profile', profile, '--dump-config', ...overlays.flatMap(p => ['--patch', p])]
  return invoke(args, { DSH_HOME: evalHome })
}

export type ComposedRows = Map<string, Record<string, unknown>>

/** Parse a dump-config text into rows keyed by id (provenance comments stripped). */
export function parseComposedRows(text: string): ComposedRows {
  const body = text.split('\n').filter(l => !l.startsWith('#')).join('\n')
  // `!!js` expressions are opaque to us; keep them as tagged strings.
  const jsTag = new yaml.Type('tag:yaml.org,2002:js', { kind: 'scalar', construct: (data: unknown) => `!!js ${String(data)}` })
  const schema = yaml.DEFAULT_SCHEMA.extend([jsTag])
  const parsed = yaml.load(body, { schema }) as unknown
  const rows: ComposedRows = new Map()
  if (!Array.isArray(parsed)) return rows
  for (const row of parsed) {
    if (row !== null && typeof row === 'object' && typeof (row as Record<string, unknown>)['id'] === 'string') {
      rows.set((row as Record<string, unknown>)['id'] as string, row as Record<string, unknown>)
    }
  }
  return rows
}

export interface RowDiff {
  id: string
  kind: 'added' | 'removed' | 'changed'
  /** Top-level fields that differ (`config`, `disabled`, `name`, …). */
  fields: string[]
  before?: unknown
  after?: unknown
}

function stable(v: unknown): string {
  return JSON.stringify(v, (_k, val: unknown) => {
    if (val !== null && typeof val === 'object' && !Array.isArray(val)) {
      return Object.fromEntries(Object.entries(val as Record<string, unknown>).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
    }
    return val
  })
}

/** Row-level diff of two composed trees. */
export function diffComposedRows(a: ComposedRows, b: ComposedRows): RowDiff[] {
  const out: RowDiff[] = []
  for (const [id, row] of a) {
    const other = b.get(id)
    if (other === undefined) { out.push({ id, kind: 'removed', fields: [], before: row }); continue }
    const fields = new Set([...Object.keys(row), ...Object.keys(other)])
    const changed = [...fields].filter(f => f !== 'id' && stable(row[f]) !== stable(other[f]))
    if (changed.length > 0) out.push({ id, kind: 'changed', fields: changed, before: row, after: other })
  }
  for (const [id, row] of b) if (!a.has(id)) out.push({ id, kind: 'added', fields: [], after: row })
  return out
}

/** Differences between two arms outside the composed tree (route-level). */
export function diffRoute(a: ResolvedArm, b: ResolvedArm): string[] {
  const out: string[] = []
  if (a.provider !== b.provider) out.push('provider')
  if (a.model !== b.model) out.push('model')
  if ((a.effort ?? null) !== (b.effort ?? null)) out.push('effort')
  if ((a.maxTokens ?? null) !== (b.maxTokens ?? null)) out.push('maxTokens')
  if (stable(a.env ?? {}) !== stable(b.env ?? {})) out.push('env')
  return out
}

export function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex')
}
