/**
 * Step 1 of a new run: design the two arms side by side.
 *
 * An arm is a preset, so it is shown as one: the left column is what dsh does
 * with nothing added, the right column is the candidate's list of deliberate
 * differences, and the shelf beside it holds every dsh plugin found on this
 * machine. Dragging a plugin onto the candidate adds it; dragging a card off,
 * or pressing its remove button, takes it away. The variable count under the
 * columns is the one-variable rule, live.
 */
import { useEffect, useMemo, useState } from 'preact/hooks'
import { api, fmt, type ArmInfo, type Meta, type PluginInfo, type Preflight, type RowInfo } from '../api.js'
import { armToYaml, describeRow, designFromSpec, inverseOf, variableCount, type ArmDesign, type DesignRow } from '../arm-model.js'

const MODELS = ['deepseek-v4-flash', 'deepseek-v4-pro', 'deepseek-v4-flash-vision-exp']
const EFFORTS = ['off', 'low', 'high', 'max']

export function ArmDesigner({ meta, arms, baseline, candidate, onBaseline, onCandidate, onSaved }: {
  meta: Meta | null
  arms: ArmInfo[]
  baseline: string
  candidate: string
  onBaseline: (name: string) => void
  onCandidate: (name: string) => void
  onSaved: () => void
}) {
  const [plugins, setPlugins] = useState<PluginInfo[]>([])
  const [rows, setRows] = useState<RowInfo[]>([])
  const [design, setDesign] = useState<ArmDesign | null>(null)
  const [dirty, setDirty] = useState(false)
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [query, setQuery] = useState('')
  const [over, setOver] = useState(false)
  const [showOff, setShowOff] = useState(false)
  const [check, setCheck] = useState<Preflight | null>(null)
  const [checking, setChecking] = useState<'dry' | 'live' | null>(null)
  /**
   * A plugin the profile activates for every arm cannot be the variable while it
   * sits in arm B. The comparison is made by removing it from arm A instead.
   */
  const moveToBaseline = async (plugin: PluginInfo): Promise<void> => {
    if (design === null || baselineSpec === undefined) return
    setSaving(true)
    setError(null)
    try {
      const withoutIt = { ...design, rows: design.rows.filter(r => !((r.kind === 'insert' || r.kind === 'bundle') && r.name === plugin.name)) }
      const base = designFromSpec(baselineSpec, plugins)
      // Written as one generated patch file: removing a plugin moves several rows but is
      // one decision, and the one-variable rule counts a file once.
      const patchName = `without-${plugin.rowId}`
      const inverse = inverseOf(plugin)
      const text = [`# arm A without ${plugin.name} — generated by the arm designer`, ...inverse.flatMap(r => (r.kind === 'disable' ? [`- id: ${r.id}`, '  disabled: true'] : r.kind === 'enable' ? [`- id: ${r.id}`, '  disabled: false'] : []))].join('\n')
      const { saved } = await api.savePatch(patchName, text)
      const already = base.rows.some(r => r.kind === 'bundle' && r.path === saved)
      await api.saveArm(base.name, armToYaml(already ? base : { ...base, rows: [...base.rows, { kind: 'bundle', name: `without ${plugin.rowId}`, path: saved, replaces: plugin.inserts ?? [], inserts: [] }] }))
      await api.saveArm(withoutIt.name, armToYaml(withoutIt))
      setDesign(withoutIt)
      setDirty(false)
      setCheck(null)
      onSaved()
    } catch (e) { setError(String(e)) } finally { setSaving(false) }
  }
  const runCheck = async (dry: boolean): Promise<void> => {
    if (design === null) return
    setChecking(dry ? 'dry' : 'live')
    setCheck(null)
    setError(null)
    try {
      if (dirty) await api.saveArm(design.name, armToYaml(design))
      setDirty(false)
      setCheck(await api.preflight(design.name, dry))
      onSaved()
    } catch (e) { setError(String(e)) } finally { setChecking(null) }
  }

  const armNames = arms.filter(a => a.spec).map(a => a.spec!.name)
  const baselineSpec = arms.find(a => a.spec?.name === baseline)?.spec
  const candidateSpec = arms.find(a => a.spec?.name === candidate)?.spec

  useEffect(() => { api.plugins().then(r => setPlugins(r.plugins)).catch(() => setPlugins([])) }, [])
  useEffect(() => { api.rows(baseline).then(r => setRows(r.rows)).catch(() => setRows([])) }, [baseline])
  useEffect(() => {
    if (candidateSpec === undefined) { setDesign(null); return }
    setDesign(designFromSpec(candidateSpec, plugins))
    setDirty(false)
  }, [candidate, candidateSpec?.name, plugins.length])

  const baselineDesign = baselineSpec === undefined ? null : designFromSpec(baselineSpec, plugins)
  const used = useMemo(() => new Set((design?.rows ?? []).flatMap(r => (r.kind === 'insert' || r.kind === 'bundle' ? [r.name] : []))), [design])
  const shelf = plugins.filter(p => !used.has(p.name) && p.name !== '@dsh-external/dsh-eval-infra'
    && (query === '' || p.name.toLowerCase().includes(query.toLowerCase()) || (p.description ?? '').toLowerCase().includes(query.toLowerCase())))

  const change = (next: ArmDesign): void => { setDesign(next); setDirty(true) }
  /** Set or clear an optional field without letting `undefined` through an exact-optional type. */
  const setField = (field: 'model' | 'effort', value: string): void => {
    if (design === null) return
    const { model, effort, ...rest } = design
    const kept = { ...rest, ...(field === 'model' ? {} : model !== undefined ? { model } : {}), ...(field === 'effort' ? {} : effort !== undefined ? { effort } : {}) }
    change(value === '' ? kept : { ...kept, [field]: value })
  }
  const addPlugin = (p: PluginInfo): void => {
    if (design === null || used.has(p.name)) return
    // A plugin that replaces part of dsh ships a patch saying what it turns off; apply that
    // rather than inserting the row beside the component it is meant to replace.
    const row: DesignRow = p.bundlePatch !== undefined
      ? { kind: 'bundle', name: p.name, path: p.bundlePatch, replaces: p.replaces ?? [], inserts: p.inserts ?? [] }
      : { kind: 'insert', id: p.rowId, name: p.name }
    change({ ...design, rows: [...design.rows, row] })
  }
  const removeRow = (index: number): void => {
    if (design === null) return
    change({ ...design, rows: design.rows.filter((_, i) => i !== index) })
  }
  const turnOff = (id: string): void => {
    if (design === null || id === '') return
    change({ ...design, rows: [...design.rows, { kind: 'disable', id }] })
    setShowOff(false)
  }
  const save = async (): Promise<void> => {
    if (design === null) return
    setSaving(true)
    setError(null)
    try { await api.saveArm(design.name, armToYaml(design)); setDirty(false); onSaved() }
    catch (e) { setError(String(e)) }
    finally { setSaving(false) }
  }

  // Rows this arm adds that the composed baseline already has: the profile put them in both arms.
  const baselineRowIds = new Set(rows.filter(r => !r.disabled).map(r => r.id))
  const sharedPlugins = (design?.rows ?? []).flatMap((r) => {
    const name = r.kind === 'insert' || r.kind === 'bundle' ? r.name : null
    if (name === null) return []
    const plugin = plugins.find(p => p.name === name)
    if (plugin === undefined) return []
    const ids = plugin.bundlePatch !== undefined ? (plugin.inserts ?? []) : [plugin.rowId]
    return ids.length > 0 && ids.every(id => baselineRowIds.has(id)) ? [plugin] : []
  })
  // The composed-tree diff is the authority: it sees both arms, so a change made on the
  // baseline side counts too. The local row count stands in only until it arrives.
  const [composedVariables, setComposedVariables] = useState<number | null>(null)
  useEffect(() => {
    if (candidate === '' || baseline === '') { setComposedVariables(null); return }
    let cancelled = false
    api.diff(baseline, [candidate])
      .then(r => { if (!cancelled) setComposedVariables(r.diffs[0]?.variables ?? 0) })
      .catch(() => { if (!cancelled) setComposedVariables(null) })
    return () => { cancelled = true }
  }, [baseline, candidate, dirty, check])
  const variables = composedVariables ?? (design === null ? 0 : variableCount(design))
  const tone = variables === 0 ? 'uk-alert' : variables === 1 ? 'uk-alert' : 'uk-alert'

  return (
    <div class="flex flex-col gap-4">
      <div class="grid gap-4 designer-grid">
        {/* A: baseline */}
        <section class="uk-card">
          <div class="uk-card-header flex items-center justify-between gap-2 py-3">
            <div>
              <div class="text-xs uppercase tracking-wide text-muted-foreground">Arm A · baseline</div>
              <select class="uk-select uk-form-sm mt-1" value={baseline} onChange={e => onBaseline((e.target as HTMLSelectElement).value)}>
                {armNames.map(n => <option value={n}>{n}</option>)}
              </select>
            </div>
            <span class="uk-badge uk-badge">reference</span>
          </div>
          <div class="uk-card-body py-3">
            <p class="text-sm text-muted-foreground">Stock dsh composes {rows.length || '…'} components. Anything below is what this arm changes on top of that.</p>
            <div class="mt-3 flex flex-col gap-2">
              {(baselineDesign?.rows ?? []).map(r => <RowCard key={describeRow(r)} row={r} />)}
              {(baselineDesign?.rows ?? []).length === 0 && (
                <div class="rounded-md border border-dashed border-border px-3 py-6 text-center text-sm text-muted-foreground">nothing added — this is dsh as it ships</div>
              )}
            </div>
          </div>
        </section>

        {/* B: candidate, the drop target */}
        <section
          class={`uk-card transition-colors ${over ? 'drop-target' : ''}`}
          onDragOver={(e) => { e.preventDefault(); setOver(true) }}
          onDragLeave={() => setOver(false)}
          onDrop={(e) => {
            e.preventDefault()
            setOver(false)
            const name = e.dataTransfer?.getData('text/plain') ?? ''
            const plugin = plugins.find(p => p.name === name)
            if (plugin) addPlugin(plugin)
          }}
        >
          <div class="uk-card-header flex items-center justify-between gap-2 py-3">
            <div>
              <div class="text-xs uppercase tracking-wide text-muted-foreground">Arm B · candidate</div>
              <select class="uk-select uk-form-sm mt-1" value={candidate} onChange={e => onCandidate((e.target as HTMLSelectElement).value)}>
                {armNames.filter(n => n !== baseline).map(n => <option value={n}>{n}</option>)}
              </select>
            </div>
            {dirty && <button class="uk-btn uk-btn-primary uk-btn-sm" disabled={saving} onClick={() => void save()}>{saving ? 'saving…' : 'Save arm'}</button>}
          </div>
          <div class="uk-card-body py-3">
            <div class="flex flex-col gap-2">
              {(design?.rows ?? []).map((r, i) => <RowCard key={`${r.kind}-${i}`} row={r} onRemove={() => removeRow(i)} />)}
              {(design?.rows ?? []).length === 0 && (
                <div class="rounded-md border border-dashed border-border px-3 py-6 text-center text-sm text-muted-foreground">
                  drag a plugin here, or turn a stock component off
                </div>
              )}
            </div>
            <div class="mt-3 flex flex-wrap items-center gap-2">
              <button class="uk-btn uk-btn-default uk-btn-sm" onClick={() => setShowOff(!showOff)}>turn a component off</button>
              <label class="text-sm text-muted-foreground flex items-center gap-1">model
                <select class="uk-select uk-form-sm" value={design?.model ?? ''} onChange={e => setField('model', (e.target as HTMLSelectElement).value)}>
                  <option value="">same as baseline</option>
                  {MODELS.map(m => <option value={m}>{m}</option>)}
                </select>
              </label>
              <label class="text-sm text-muted-foreground flex items-center gap-1">effort
                <select class="uk-select uk-form-sm" value={design?.effort ?? ''} onChange={e => setField('effort', (e.target as HTMLSelectElement).value)}>
                  <option value="">same as baseline</option>
                  {EFFORTS.map(m => <option value={m}>{m}</option>)}
                </select>
              </label>
            </div>
            {showOff && (
              <select class="uk-select uk-form-sm mt-2" onChange={e => turnOff((e.target as HTMLSelectElement).value)}>
                <option value="">— pick a component of the composed tree —</option>
                {rows.map(r => <option value={r.id}>{r.id}{r.configKeys.length ? ` · ${r.configKeys.length} config field(s)` : ''}</option>)}
              </select>
            )}
            {error !== null && <p class="text-destructive text-sm mt-2">{error}</p>}
            <div class="mt-3 flex flex-wrap items-center gap-2 border-t border-border pt-3">
              <button class="uk-btn uk-btn-default uk-btn-sm" disabled={checking !== null} onClick={() => void runCheck(true)}>{checking === 'dry' ? 'checking…' : 'Check composition'}</button>
              <button class="uk-btn uk-btn-primary uk-btn-sm" disabled={checking !== null} onClick={() => void runCheck(false)}>{checking === 'live' ? 'running one turn…' : 'Test this arm end to end'}</button>
              <span class="text-xs text-muted-foreground">the full test boots a real runtime on one tiny scenario, about a cent</span>
            </div>
            {sharedPlugins.length > 0 && (
              <div class="uk-alert mt-3 py-2 text-sm">
                <b>{sharedPlugins.map(p => p.rowId).join(', ')}</b> {sharedPlugins.length === 1 ? 'is' : 'are'} installed into the profile, so {sharedPlugins.length === 1 ? 'it is' : 'they are'} already in both arms and cannot be what the run measures.
                {' '}Compare with and without by removing {sharedPlugins.length === 1 ? 'it' : 'them'} from arm A instead.
                <div class="mt-2 flex flex-wrap gap-2">
                  {sharedPlugins.map(p => (
                    <button key={p.name} class="uk-btn uk-btn-primary uk-btn-sm" disabled={saving} onClick={() => void moveToBaseline(p)}>move {p.rowId} to arm A as a removal</button>
                  ))}
                </div>
              </div>
            )}
            {check !== null && (
              <div class="mt-3 flex flex-col gap-1">
                {check.stages.map(st => (
                  <div key={st.name} class="flex items-start gap-2 text-sm">
                    <span class={`cls ${st.ok ? 'same' : 'regression'} shrink-0`}>{st.ok ? 'ok' : 'fail'}</span>
                    <span class="text-muted-foreground"><b class="text-foreground">{st.name}</b> · {st.detail}</span>
                  </div>
                ))}
                {check.rows.map(r => (
                  <div key={r.id} class="text-xs text-muted-foreground pl-1">
                    row <code>{r.id}</code>: {r.present ? (r.enabled ? 'mounted and enabled' : 'present but disabled') : 'MISSING from the composed tree'}
                    {r.inBaseline && <span class="text-destructive"> · also active in the baseline, so it is in both arms</span>}
                  </div>
                ))}
                {check.smoke !== undefined && check.smoke.ok && (
                  <div class="text-xs text-muted-foreground pl-1">{check.smoke.scenario} finished in {fmt.secs(check.smoke.wallMs)} for {fmt.usd(check.smoke.usd)} · {check.smoke.tools.length} tools reached the agent</div>
                )}
              </div>
            )}
          </div>
        </section>

        {/* the shelf */}
        <section class="uk-card">
          <div class="uk-card-header py-3">
            <div class="text-xs uppercase tracking-wide text-muted-foreground">Plugins on this machine</div>
            <input class="uk-input uk-form-sm mt-2" type="search" placeholder="filter" value={query} onInput={e => setQuery((e.target as HTMLInputElement).value)} />
          </div>
          <div class="uk-card-body py-3 shelf-scroll flex flex-col gap-2">
            {shelf.map(p => (
              <article
                key={p.name}
                class="plugin-chip rounded-md border border-border bg-background px-2 py-1.5 cursor-grab"
                draggable
                onDragStart={(e) => { e.dataTransfer?.setData('text/plain', p.name); e.dataTransfer!.effectAllowed = 'copy' }}
                onDblClick={() => addPlugin(p)}
                title={`${p.displayPath ?? p.path}${(p.duplicates ?? []).length > 0 ? `\n${(p.duplicates ?? []).length} other copy(s) on this machine were hidden:\n${(p.duplicates ?? []).join('\n')}` : ''}\ndouble-click or drag into arm B`}
              >
                <div class="flex items-center justify-between gap-2">
                  <span class="text-sm font-medium truncate">{p.rowId}</span>
                  <button class="uk-btn uk-btn-default uk-btn-xs" onClick={() => addPlugin(p)}>add</button>
                </div>
                <div class="text-xs text-muted-foreground truncate">{p.description ?? p.name}</div>
                <div class="mt-1 flex gap-1">
                  {p.installed && <span class="uk-badge uk-badge badge-xs">installed</span>}
                  {p.bundlePatch !== undefined
                    ? <span class="uk-badge uk-badge-destructive badge-xs" title={(p.replaces ?? []).length > 0 ? `applies its own patch: turns off ${(p.replaces ?? []).join(', ')} and inserts ${(p.inserts ?? []).join(', ')}` : 'applies its own patch'}>{(p.replaces ?? []).length > 0 ? `replaces ${(p.replaces ?? []).length}` : 'own patch'}</span>
                    : <span class="uk-badge badge-xs" title="adds one row beside the stock components">add-on</span>}
                  <span class="uk-badge uk-badge badge-xs">{p.source}</span>
                </div>
              </article>
            ))}
            {shelf.length === 0 && <p class="text-sm text-muted-foreground">nothing left to add</p>}
          </div>
        </section>
      </div>

      <div class={`uk-alert ${tone} py-2`}>
        {variables === 1 && <span><b>One variable.</b> Arm B differs from arm A in exactly one thing, so a difference in the result can be attributed to it.</span>}
        {variables === 0 && <span><b>No difference yet.</b> Arm B composes the same as arm A; this would be an A/A run, which measures the noise floor.</span>}
        {variables > 1 && <span><b>{variables} variables.</b> A result cannot be attributed to one change. Split them into separate candidates, or accept a multi-variable comparison in the next step.</span>}
        {composedVariables === null && <span class="text-muted-foreground"> · counting from the arm files; the composed trees decide</span>}
        {dirty && <span class="text-muted-foreground"> · unsaved changes to <code>{design?.name}</code>, save to recount</span>}
      </div>
    </div>
  )
}

function RowCard({ row, onRemove }: { row: DesignRow; onRemove?: () => void }) {
  const tone = row.kind === 'insert' || row.kind === 'enable' ? 'row-insert' : row.kind === 'disable' ? 'row-disable' : row.kind === 'bundle' ? 'row-bundle' : 'row-other'
  return (
    <article class={`rounded-md border border-border border-l-2 ${tone} bg-background px-3 py-2 flex items-start justify-between gap-2`}>
      <div class="min-w-0">
        <div class="text-sm font-medium truncate">{'id' in row ? row.id : row.kind === 'bundle' ? row.name.split('/').pop() : 'custom'}</div>
        <div class="text-xs text-muted-foreground truncate">{describeRow(row)}</div>
        {row.kind === 'insert' && row.config !== undefined && (
          <div class="text-xs text-muted-foreground">{Object.entries(row.config).map(([k, v]) => `${k} = ${String(v)}`).join(' · ')}</div>
        )}
      </div>
      {onRemove !== undefined && <button class="uk-btn uk-btn-default uk-btn-xs" title="remove from this arm" onClick={onRemove}>×</button>}
    </article>
  )
}
